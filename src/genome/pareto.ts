/**
 * The Pareto rule for generated parameters [P7-D1]. Pure module (no Rng: everything is a function of ranks).
 *
 * BOUNDED PARETO QUANTILE (normalised to [0, 1]):
 *
 *     x(q) = (1 - q (1 - K^-a))^(-1/a)            in [1, K]          (inverse CDF of Pareto(a) on [1, K])
 *     paretoQ(q) = (x(q) - 1) / (K - 1)            in [0, 1]          paretoQ(0) = 0, paretoQ(1) = 1
 *
 * With K = PARETO_K = 120 and a = PARETO_ALPHA = 0.8 the top 20 % of a uniform q hold ~80 % of the total
 * (tests/pareto_test.ts measures it: 0.79-0.81); median 0.013, 80th percentile 0.057, mean 0.05.
 *
 * TWO-SIDED REMAP AROUND THE MEDIAN (rank preserving):
 *
 *     p = population rank of the raw value (empirical CDF from the calibration knots)
 *     m = population median of the raw value
 *     p >= 0.5:  out = m + (1 - m) * paretoQ((p - 0.5) / 0.5)
 *     p <  0.5:  out = m -      m  * paretoQ((0.5 - p) / 0.5)
 *
 * So the median is pinned (the typical creature keeps its look), both bounds 0 and 1 are reached by the
 * rarest ranks (min and max), the mean is pulled toward the longer side, and the 20 % most deviant
 * creatures carry ~80 % of the total absolute deviation from the median. The map is monotone in the raw
 * value, so everything genetic is kept: a child of extreme parents ranks high and is expressed far out.
 *
 * ONE-SIDED REMAP (extra-feature magnitudes whose neutral value is the minimum: relief counts, extra horn
 * pairs, spike rows, extra operators, ambient motes, the strength of an open recessive gate):
 *
 *     out = paretoQ(p)          (most creatures at / near the minimum = the pass-6 look, a few at the maximum)
 *
 * CALIBRATION: `src/data/paretoCalib.ts` holds, per gene key, CALIB_KNOTS quantiles of the raw value over the
 * wild population (generated by `deno task pareto --write`, iterated to a fixed point because some drives
 * read upstream remapped traits). A key without knots is the identity (legacy / fixtures).
 */

export const PARETO_K = 120;
export const PARETO_ALPHA = 0.8;
/**
 * Probabilities of the quantile knots stored per calibrated key: dense in both tails (the Pareto remap lives
 * there: a creature at rank 0.999 must not be read as rank 0.98), 2.5 % steps in the body.
 */
export const CALIB_PROBS: readonly number[] = (() => {
  const tail = [0, 0.0003, 0.001, 0.002, 0.004, 0.007, 0.01, 0.015, 0.02];
  const body: number[] = [];
  for (let p = 0.025; p < 0.976; p += 0.025) body.push(Math.round(p * 1000) / 1000);
  return [...tail, ...body, ...tail.slice().reverse().map((p) => Math.round((1 - p) * 10000) / 10000)];
})();
export const CALIB_KNOTS = CALIB_PROBS.length;

const clamp01 = (x: number) => (x < 0 ? 0 : x > 1 ? 1 : x);

/** Normalised bounded Pareto quantile: paretoQ(0) = 0, paretoQ(1) = 1, mass concentrated near 0. */
export function paretoQ(q: number, alpha = PARETO_ALPHA, K = PARETO_K): number {
  const u = clamp01(Number.isFinite(q) ? q : 0);
  const A = Math.pow(K, -alpha);
  const x = Math.pow(1 - u * (1 - A), -1 / alpha);
  return clamp01((x - 1) / (K - 1));
}

/** Two-sided remap of a population rank p (0..1) around the median m (0..1). Monotone in p. */
export function paretoAround(p: number, m: number): number {
  const pp = clamp01(Number.isFinite(p) ? p : 0.5), mm = clamp01(Number.isFinite(m) ? m : 0.5);
  if (pp >= 0.5) return mm + (1 - mm) * paretoQ((pp - 0.5) / 0.5);
  return mm - mm * paretoQ((0.5 - pp) / 0.5);
}

/**
 * Empirical CDF from sorted quantile knots (knots[i] = quantile at probs[i]; CALIB_PROBS when the lengths
 * match, else evenly spaced i / (n - 1)): linear between knots, the middle of a flat run for tied knots,
 * 0 / 1 outside.
 */
export function rankOf(knots: readonly number[], v: number): number {
  const n = knots.length;
  const P = n === CALIB_PROBS.length ? (i: number) => CALIB_PROBS[i] : (i: number) => i / (n - 1);
  if (n < 2 || !Number.isFinite(v)) return 0.5;
  if (v < knots[0]) return 0;
  if (v > knots[n - 1]) return 1;
  // First index with knots[i] >= v and last index with knots[j] <= v.
  let lo = 0, hi = n - 1;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (knots[mid] < v) lo = mid + 1;
    else hi = mid;
  }
  const first = lo;
  if (knots[first] === v) {
    let last = first;
    while (last + 1 < n && knots[last + 1] === v) last++;
    return (P(first) + P(last)) / 2;
  }
  const a = knots[first - 1], b = knots[first];
  const t = b > a ? (v - a) / (b - a) : 0.5;
  return P(first - 1) + (P(first) - P(first - 1)) * t;
}

/** The median of a knot list (the knot at probability 0.5). */
export function knotMedian(knots: readonly number[]): number {
  const n = knots.length;
  if (n === 0) return 0.5;
  if (n === CALIB_PROBS.length) return knots[CALIB_PROBS.indexOf(0.5)];
  return n % 2 ? knots[(n - 1) / 2] : (knots[n / 2 - 1] + knots[n / 2]) / 2;
}

/**
 * Remap a raw normalised value v (0..1) of `key` through its calibration: rank -> two-sided Pareto around
 * the raw median. Returns the value and its rank (rank 0.5 for an uncalibrated key: identity).
 */
export function paretoRemap(knots: readonly number[] | undefined, v: number, oneSided = false): { value: number; rank: number } {
  if (!knots || knots.length < 2) return { value: v, rank: 0.5 };
  const rank = rankOf(knots, v);
  return { value: oneSided ? paretoQ(rank) : paretoAround(rank, clamp01(knotMedian(knots))), rank };
}

/** Quantiles of a sample at CALIB_PROBS (for the calibration tool), or at n evenly spaced probabilities. */
export function quantileKnots(xs: readonly number[], n?: number): number[] {
  const s = xs.filter(Number.isFinite).slice().sort((a, b) => a - b);
  if (s.length === 0) return [];
  const probs = n === undefined ? CALIB_PROBS : Array.from({ length: n }, (_, i) => i / (n - 1));
  const out: number[] = [];
  for (const p of probs) {
    const pos = p * (s.length - 1);
    const a = Math.floor(pos), b = Math.min(s.length - 1, a + 1);
    out.push(Math.round((s[a] + (s[b] - s[a]) * (pos - a)) * 1e6) / 1e6);
  }
  return out;
}

// ------------------------------------------------------------------ measurement (tools + tests)
export interface DistSummary {
  n: number;
  min: number;
  max: number;
  median: number;
  mean: number;
  p10: number;
  p90: number;
  /** Share of the total |x - median| held by the 20 % most deviant values (0.8 = the Pareto rule). */
  share20: number;
  /** Number of distinct values (rounded to 1e-4): 1 = a constant. */
  distinct: number;
}

/** Share of the total absolute deviation from the median held by the 20 % most deviant values. */
export function paretoShare(xs: readonly number[]): number {
  const s = xs.filter(Number.isFinite);
  if (s.length < 5) return 0;
  const sorted = s.slice().sort((a, b) => a - b);
  const med = sorted.length % 2 ? sorted[(sorted.length - 1) / 2] : (sorted[sorted.length / 2 - 1] + sorted[sorted.length / 2]) / 2;
  const dev = s.map((x) => Math.abs(x - med)).sort((a, b) => b - a);
  const total = dev.reduce((a, b) => a + b, 0);
  if (total <= 0) return 0;
  const k = Math.max(1, Math.round(dev.length * 0.2));
  let top = 0;
  for (let i = 0; i < k; i++) top += dev[i];
  return top / total;
}

export function summarize(xs: readonly number[]): DistSummary {
  const s = xs.filter(Number.isFinite).slice().sort((a, b) => a - b);
  const n = s.length;
  if (n === 0) return { n: 0, min: 0, max: 0, median: 0, mean: 0, p10: 0, p90: 0, share20: 0, distinct: 0 };
  const q = (p: number) => s[Math.min(n - 1, Math.max(0, Math.round(p * (n - 1))))];
  const median = n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2;
  return {
    n,
    min: s[0],
    max: s[n - 1],
    median,
    mean: s.reduce((a, b) => a + b, 0) / n,
    p10: q(0.1),
    p90: q(0.9),
    share20: paretoShare(s),
    distinct: new Set(s.map((v) => Math.round(v * 1e4))).size,
  };
}
