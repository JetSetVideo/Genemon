// Batch lab tool [P5-X1, P6-B2]: archetype matchup matrix + held-out seed, COLOSSUS vs SIX matrices per level and
// team-quality bracket (+ held-out seed), one batch-breeding run. Measured, never tuned.
//   deno run --allow-read --allow-write=artifacts tools/batch.ts [nPerCell=24] [generations=6] [popSize=12] [colossusN=nPerCell]
// Writes artifacts/batch/REPORT.md, artifacts/batch/matrix.json and artifacts/batch/colossus.json.
import { TUNING } from "../src/combat/battle.ts";
import { hashSeed } from "../src/core/rng.ts";
import { POWER_BUDGET } from "../src/data/sizeBudget.ts";
import { createGenemon } from "../src/genome/genemon.ts";
import {
  BATCH_ARCHETYPES,
  batchReportMarkdown,
  breedBatch,
  colossusMatrix,
  colossusReportMarkdown,
  gauntletFitness,
  LEVEL_BRACKETS,
  matchupMatrix,
} from "../src/sim/batch.ts";

const N = Math.max(1, Number(Deno.args[0] ?? 24));
const GENS = Math.max(0, Number(Deno.args[1] ?? 6));
const POP = Math.max(2, Number(Deno.args[2] ?? 12));
const CN = Math.max(1, Number(Deno.args[3] ?? N));
const SEED = 5;

const t0 = performance.now();
const m = matchupMatrix(BATCH_ARCHETYPES, N, SEED);
const tMatrix = performance.now() - t0;

// Held-out check: the same matrix on a different seed (a band that only holds on one seed is noise).
const t1 = performance.now();
const held = matchupMatrix(BATCH_ARCHETYPES, N, SEED + 1000);
const tHeld = performance.now() - t1;

// Colossus vs six [P6-B1]: level brackets x team-quality brackets, paired colossi, Wilson intervals, held-out seed.
const t3 = performance.now();
const col = colossusMatrix(CN, SEED, LEVEL_BRACKETS);
const colHeld = colossusMatrix(CN, SEED + 1000, LEVEL_BRACKETS);
const tCol = performance.now() - t3;

// Batch breeding from a random wild population (mixed sizes and elements), selected on gauntlet win rate.
const t2 = performance.now();
const wild = Array.from({ length: POP }, (_, i) => createGenemon({ seed: hashSeed("batch-wild", i), owner: "wild", level: 25 }));
const bred = breedBatch(wild, GENS, POP, gauntletFitness(), SEED);
const tBreed = performance.now() - t2;

const pc = (p: number) => `${Math.round(p * 100)}%`;
const sig = (r: typeof m.rows[number]) => r.beats.filter((b) => b.significant).map((b) => b.id);
const header = [
  `Generated by \`deno run --allow-read --allow-write=artifacts tools/batch.ts ${N} ${GENS} ${POP} ${CN}\`: matrix ${(tMatrix / 1000).toFixed(1)} s, held-out matrix ${(tHeld / 1000).toFixed(1)} s, ` +
  `colossus batches ${(tCol / 1000).toFixed(1)} s, breeding ${(tBreed / 1000).toFixed(1)} s. Measured, not tuned.`,
  "",
  `Held-out seed ${held.seed}: overall ${held.rows.map((r) => `${r.label} ${pc(r.overall.p)}`).join(", ")}; ` +
  `no dominant row ${held.verdict.noDominantRow ? "yes" : "NO"}, no lopsided cell ${held.verdict.noLopsidedCell ? "yes" : "NO"}, all with pros and cons ${held.verdict.allHaveProsAndCons ? "yes" : "NO"}` +
  (held.flags.length ? `; flags: ${held.flags.join("; ")}` : "; flags: none") + ".",
  "",
  `Significant counters (row beats column, 95 % interval above 50 %): ${m.rows.map((r) => `${r.label}: ${sig(r).join(", ") || "NONE"}`).join("; ")}. ` +
  `Held-out: ${held.rows.map((r) => `${r.label}: ${sig(r).join(", ") || "none"}`).join("; ")}.`,
  "",
  `Size budgets: ${Object.entries(POWER_BUDGET).map(([k, v]) => `${k} ${v}`).join(", ")}. Battle knobs (src/combat/battle.ts TUNING): ${Object.entries(TUNING).map(([k, v]) => `${k} ${typeof v === "number" ? +v.toFixed(3) : v}`).join(", ")}.`,
].join("\n");
const report = batchReportMarkdown(m, { result: bred, label: `${POP} random wild Genemon, ${GENS} generations` }, header) + "\n" + colossusReportMarkdown(col, colHeld);

await Deno.mkdir("artifacts/batch", { recursive: true });
await Deno.writeTextFile("artifacts/batch/REPORT.md", report);
await Deno.writeTextFile(
  "artifacts/batch/matrix.json",
  JSON.stringify(
    {
      generatedBy: `tools/batch.ts ${N} ${GENS} ${POP} ${CN}`,
      seed: m.seed,
      nPerCell: m.nPerCell,
      options: m.options,
      ids: m.ids,
      cells: m.cells.map((row) => row.map((c) => ({ ...c, p: +c.p.toFixed(4), lo: +c.lo.toFixed(4), hi: +c.hi.toFixed(4) }))),
      rows: m.rows.map((r) => ({ id: r.id, overall: r.overall, beats: r.beats, losesTo: r.losesTo, medianDuration: r.medianDuration, meanDealt: r.meanDealt, meanTaken: r.meanTaken, koRate: r.koRate, profile: r.profile, pros: r.pros, cons: r.cons, flags: r.flags })),
      verdict: m.verdict,
      flags: m.flags,
      draws: m.draws,
      battles: m.battles,
      build: m.build,
      heldOut: { seed: held.seed, overall: Object.fromEntries(held.rows.map((r) => [r.id, r.overall])), verdict: held.verdict, flags: held.flags },
      breeding: bred.generations,
    },
    null,
    1,
  ),
);
const round = (c: typeof col) => ({
  seed: c.seed,
  nPerCell: c.nPerCell,
  levels: c.levels,
  brackets: c.brackets,
  cells: c.cells.map((row) => row.map((x) => ({ ...x, p: +x.p.toFixed(4), lo: +x.lo.toFixed(4), hi: +x.hi.toFixed(4) }))),
  pooled: c.pooled.map((x) => ({ ...x, p: +x.p.toFixed(4), lo: +x.lo.toFixed(4), hi: +x.hi.toFixed(4) })),
  battles: c.battles,
  draws: c.draws,
  colossusBuild: c.colossusBuild,
  sixBuild: c.sixBuild,
  verdict: c.verdict,
  flags: c.flags,
});
await Deno.writeTextFile("artifacts/batch/colossus.json", JSON.stringify({ generatedBy: `tools/batch.ts ${N} ${GENS} ${POP} ${CN}`, main: round(col), heldOut: round(colHeld) }, null, 1));
console.log(report.split("\n").slice(0, 44).join("\n"));
console.log("\n" + colossusReportMarkdown(col, colHeld));
console.log(`\nwrote artifacts/batch/REPORT.md + matrix.json + colossus.json in ${((performance.now() - t0) / 1000).toFixed(1)} s`);
